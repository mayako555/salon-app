async function seed() {
  const colRef = collection(db, "sales_master");
  const lines = RAW_DATA.trim().split("\n");
  
  for (const line of lines) {
    const [category, name, priceStr, duration, hpbName, restrictions, notes] = line.split("｜").map(s => s?.trim());
    if (!name) continue;

    let itemType = "menu";
    if (category.includes("クーポン") || category.includes("2回目") || category.includes("再来") || category.includes("全員") || category.includes("学割")) itemType = "coupon";
    if (category.includes("メッセージ")) itemType = "messageCoupon";
    if (category.includes("オプション") || category.includes("毛質変更")) itemType = "option";
    if (category.includes("割引")) itemType = "discount";
    if (category.includes("料")) itemType = "fee";
    if (category.includes("通常メニュー") || category.includes("サービス") || category.includes("その他")) itemType = "menu";

    let price = 0;
    if (priceStr) {
      const match = priceStr.match(/-?\d+/);
      if (match) price = parseInt(match[0]);
    }

    const payload = {
      store: category.includes("六甲") ? "六甲" : "共通",
      itemType,
      category,
      name,
      price,
      duration: duration || "",
      hpbName: hpbName || "",
      restrictions: restrictions || "",
      notes: notes || "",
      isActive: true,
      staffAssignable: false,
      equipmentAssignable: false,
      created_at: serverTimestamp()
    };

    try {
      await addDoc(colRef, payload);
      console.log(`Added: ${name}`);
    } catch (e) {
      console.error(`Failed: ${name}`, e);
    }
  }
}

seed().then(() => {
  console.log("Seeding complete.");
  process.exit(0);
});
